import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';

export const themePath = fileURLToPath(new URL('./theme.json', import.meta.url));
export const theme = JSON.parse(readFileSync(themePath, 'utf8'));
const kebab = (value) => value.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);
export function generateHostTokens() {
  const block = (selector, values) => `${selector} {\n${Object.entries(values).map(([key, value]) => `  --${kebab(key)}: ${value};`).join('\n')}\n}`;
  return `/* Generated by integrations/jan/theme.mjs from theme.json. Do not edit by hand.
 * Jan b8d58255baf6d9e870025d3f0c60a5b80a63143b; Apache-2.0, Menlo Research.
 * Accessibility adaptations and domain colors are documented in integrations/jan/README.md. */
:root {
  --font-size-base: ${theme.fontSizeBase};
  --radius: ${theme.radius};
  --viewport-background: #11161c;
  --viewport-toolbar: #1e242c;
  --viewport-foreground: #d8e1ee;
  --viewport-muted: #aab7cb;
  --viewport-border: #586779;
  --viewport-selection: #f17455;
  --bg-canvas: var(--background);
  --bg-sidebar: var(--sidebar);
  --bg-panel: var(--card);
  --bg-elevated: var(--secondary);
  --bg-input: var(--input-background);
  --border-subtle: var(--border);
  --border-strong: var(--input);
  --text-primary: var(--foreground);
  --text-secondary: var(--muted-foreground);
  --text-muted: var(--muted-foreground);
  --accent-primary: var(--primary);
  --accent-primary-hover: var(--primary-hover);
  --accent-active: var(--ring);
  --accent-soft: var(--accent);
  --state-success: var(--success);
  --state-warning: var(--warning);
  --state-danger: var(--destructive);
}
${block(':root', theme.light)}
${block(':root[data-theme="dark"]', theme.dark)}
`;
}
const targetPath = fileURLToPath(new URL('../../apps/desktop/src/styles/tokens.css', import.meta.url));
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const generated = generateHostTokens();
  if (process.argv.includes('--check')) {
    if (readFileSync(targetPath, 'utf8') !== generated) throw new Error('Host theme output is stale; run node integrations/jan/theme.mjs');
  } else writeFileSync(targetPath, generated);
}
